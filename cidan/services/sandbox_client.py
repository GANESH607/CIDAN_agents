import os
import requests
from dotenv import load_dotenv

load_dotenv()

class SandboxClient:
    def __init__(self):
        self.base_url = os.getenv("SANDBOX_BASE_URL", "https://test-api.sandbox.co.in")
        self.api_key = os.getenv("SANDBOX_API_KEY")
        self.api_secret = os.getenv("SANDBOX_API_SECRET")
        self.access_token = None

    def authenticate(self):
        """Generates a 24-hour JWT access token from Sandbox."""
        url = f"{self.base_url}/authenticate"
        headers = {
            "x-api-key": self.api_key,
            "x-api-secret": self.api_secret,
            "x-api-version": "1.0"
        }
        response = requests.post(url, headers=headers)
        response.raise_for_status()
        data = response.json()
        # Sandbox returns token inside data.access_token
        self.access_token = data.get("data", {}).get("access_token")
        return self.access_token

    def run_test_suite(self, test_cases):
        """
        Executes a list of test cases generated by the LLM agent,
        compares status codes, and aggregates pass/fail tallies.
        """
        if not self.access_token:
            self.authenticate()

        headers = {
            "Authorization": self.access_token,  # Note: Sandbox does NOT use 'Bearer' prefix
            "x-api-key": self.api_key,
            "x-api-version": "1.0",
            "Content-Type": "application/json"
        }

        passed = 0
        failed = 0
        detailed_results = []

        for test in test_cases:
            endpoint = test.get("endpoint")
            method = test.get("method", "GET").upper()
            payload = test.get("payload", {})
            expected_status = test.get("expected_status", 200)
            test_id = test.get("id", "TC_UNKNOWN")

            target_url = f"{self.base_url}{endpoint}"

            try:
                if method == "POST":
                    resp = requests.post(target_url, json=payload, headers=headers)
                else:
                    resp = requests.get(target_url, params=payload, headers=headers)

                is_match = (resp.status_code == expected_status)
                if is_match:
                    passed += 1
                    status_label = "PASSED"
                else:
                    failed += 1
                    status_label = "FAILED"

                detailed_results.append({
                    "test_id": test_id,
                    "status": status_label,
                    "endpoint": endpoint,
                    "expected_status": expected_status,
                    "actual_status": resp.status_code,
                    "response": resp.json() if resp.content else {}
                })

            except Exception as e:
                failed += 1
                detailed_results.append({
                    "test_id": test_id,
                    "status": "ERROR",
                    "error": str(e)
                })

        return {
            "total_tests": len(test_cases),
            "passed_count": passed,
            "failed_count": failed,
            "pass_rate": f"{(passed / len(test_cases)) * 100:.2f}%" if test_cases else "0.00%",
            "results": detailed_results
        }